"""Render a run's artifacts into docs/RESULTS.md (numbers only come from saved run files)."""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

from ..config import PROJECT_ROOT, Config

PRIMARY = {"binary": "log_loss", "multiclass": "log_loss", "regression": "rmse", "volatility": "mse_log"}


def md_table(df: pd.DataFrame, floatfmt: str = "{:.4f}") -> str:
    def fmt(v):
        if isinstance(v, (float, np.floating)):
            return "" if np.isnan(v) else (f"{v:.2e}" if (v != 0 and abs(v) < 1e-3) else floatfmt.format(v))
        return str(v)
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    lines += ["| " + " | ".join(fmt(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join(lines)


def _read(run: Path, name: str) -> pd.DataFrame | None:
    p = run / name
    return pd.read_csv(p) if p.exists() else None


def write_report(cfg: Config, run: Path, out: Path | None = None) -> Path:
    out = out or PROJECT_ROOT / "docs" / "RESULTS.md"
    man = json.loads((run / "manifest.json").read_text(encoding="utf-8"))
    feat_meta = json.loads((cfg.data_dir / "features" / f"{cfg.market.id}_features.json").read_text(encoding="utf-8"))
    v = cfg.validation
    s = [f"# Results - {cfg.market.name}",
         "",
         "_Auto-generated by `marketpred report` from run artifacts; do not edit by hand. "
         "Interpretation is in docs/REPORT.md._",
         "",
         f"* Run: `{run.name}` (created {man['created_utc']})",
         f"* Dataset version `{man['dataset_version']}`, config fingerprint `{man['config_fingerprint']}`",
         f"* Features: {feat_meta['rows']} sessions, {feat_meta['first_date']} .. {feat_meta['last_date']}",
         f"* Development walk-forward (out-of-sample): {v.dev_start} .. {v.holdout_start} (exclusive; labels "
         f"never reach the holdout); expanding window, refit every {v.retrain_every_days} sessions, "
         f"purge = horizon + {v.embargo_days}-session embargo",
         f"* Final holdout: {v.holdout_start} .. end of data, evaluated after selection",
         "* Losses: log loss (binary/regime), squared error (returns, log volatility). "
         "`impr` = reference loss minus model loss (positive = better); p-values: Diebold-Mariano with "
         "Newey-West HAC; CIs: circular block bootstrap.",
         ""]

    cov = pd.DataFrame(feat_meta["coverage"]).T
    cov["coverage"] = cov["coverage"].astype(float)
    cat = cov.groupby("category").agg(n_features=("coverage", "size"), mean_coverage=("coverage", "mean"),
                                      earliest=("first_valid", "min"), latest_last=("last_valid", "max"))
    s += ["## 1. Feature coverage by category", "", md_table(cat.reset_index()), ""]

    comp = _read(run, "comparison_dev.csv")
    if comp is not None:
        s += ["## 2. Model comparison (development period, out-of-sample)", ""]
        for task, g in comp.groupby("task", sort=False):
            kind = g["kind"].iloc[0]
            lc = PRIMARY[kind]
            cols = ["feature_set", "model", lc]
            cols += {"binary": ["auc", "brier", "ece", "balanced_accuracy"], "multiclass": ["brier", "accuracy"],
                     "regression": ["r2_oos", "corr", "hit_rate"], "volatility": ["qlike", "mz_r2", "bias_log"]}[kind]
            ref = [c for c in g.columns if c.startswith("vs_") and c.endswith("_loss_improvement") and g[c].notna().any()]
            pcol = [c for c in g.columns if c.startswith("vs_") and c.endswith("_p_value") and g[c].notna().any()]
            t = g[cols + ref + pcol].rename(columns={ref[0]: "impr_vs_ref", pcol[0]: "p_vs_ref"} if ref else {})
            s += [f"### {task}", "", md_table(t.sort_values(lc)), ""]

    abl = _read(run, "ablation_dev.csv")
    if abl is not None:
        s += ["## 3. Feature-category ablation (development period)", "",
              "Each row adds one category to the price baseline with the same model, folds and tuning budget. "
              "`holm_p` corrects across the 8 single-category additions per task/model. "
              "`cov` = mean availability of the added features in the test period. "
              "Regime columns: mean loss improvement by ex-ante 63-day realised-vol regime.", ""]
        for task, g in abl.groupby("task", sort=False):
            kind = g["kind"].iloc[0]
            cols = ["model", "feature_set", "n_features", "test_coverage_added", PRIMARY[kind], "loss_improvement",
                    "rel_improvement", "ci_low", "ci_high", "p_value", "holm_p", "significant_improvement"]
            if kind == "binary":
                cols += ["auc", "auc_diff"]
            cols += [c for c in ("impr_low_vol", "impr_mid_vol", "impr_high_vol") if c in g]
            t = g[[c for c in cols if c in g]].rename(columns={"test_coverage_added": "cov",
                                                               "significant_improvement": "sig"})
            s += [f"### {task}", "", md_table(t), ""]
        astro_sets = ["calendar_only", "astro_only", "price+calendar", "price+astro", "price+calendar+astro"]
        a = abl[abl["feature_set"].isin(astro_sets + ["price"])]
        loss = a["kind"].map(PRIMARY)
        a = a.assign(loss=[row[col] for (_, row), col in zip(a.iterrows(), loss)])
        s += ["## 4. Astrology protocol (same out-of-sample periods)", "",
              "Compare astro_only with calendar_only (both vs the price baseline), and price+calendar+astro "
              "with price+calendar. Negative `loss_improvement` means worse than the price baseline. "
              "`loss` is log loss (binary/regime), RMSE (returns) or MSE of log vol.", "",
              md_table(a[["task", "model", "feature_set", "loss", "loss_improvement", "p_value", "holm_p"]]), ""]

    sel_p = run / "selection.json"
    if sel_p.exists():
        sel = json.loads(sel_p.read_text(encoding="utf-8"))
        rows = [{"task": t, "primary_model": x["primary_ablation_model"],
                 "surviving_categories": ", ".join(x["surviving_categories"]) or "(none)",
                 "selected_model": x["best_dev_model"], "selected_features": x["best_dev_feature_set"],
                 "dev_loss": x["best_dev_loss"], "combined_dev_loss (biased)": x["combined_dev_loss_biased"]}
                for t, x in sel["tasks"].items()]
        s += ["## 5. Pre-registered selection (made on development data only)", "", f"Rule: {sel['rule']}.", "",
              md_table(pd.DataFrame(rows)), ""]

    ho = _read(run, "holdout.csv")
    if ho is not None:
        s += ["## 6. Final holdout (untouched until after selection)", ""]
        for task, g in ho.groupby("task", sort=False):
            lc ="log_loss" if "log_loss" in g and g["log_loss"].notna().any() else (
                "mse_log" if "mse_log" in g and g["mse_log"].notna().any() else "rmse")
            extra = [c for c in ("auc", "brier", "ece", "r2_oos", "qlike", "mz_r2", "accuracy") if c in g and
                     g[c].notna().any()]
            cols = ["role", "model", "feature_set", "categories", lc] + extra + \
                   [c for c in ("vs_ref_loss_improvement", "vs_ref_ci_low", "vs_ref_ci_high", "vs_ref_p_value")
                    if c in g]
            s += [f"### {task}", "", md_table(g[cols].rename(columns=lambda c: c.replace("vs_ref_", "ref_"))), ""]

    for period in ("dev", "holdout"):
        tp = run / f"trading_{period}.json"
        if tp.exists():
            tr = json.loads(tp.read_text(encoding="utf-8"))
            rows = []
            for key, r in tr.items():
                rows.append({"model|features": key, **{f"strat_{k}": v for k, v in r["strategy"].items()
                                                       if k != "n_days"},
                             "exposure": r["exposure"], "turnover/yr": r["turnover_per_year"],
                             "bh_sharpe": r["buy_and_hold"]["sharpe"], "bh_ann_return": r["buy_and_hold"]["ann_return"],
                             "bh_max_dd": r["buy_and_hold"]["max_drawdown"]})
            s += [f"## 7{'a' if period == 'dev' else 'b'}. Long/cash simulation, {period} period "
                  f"(direction_1, P(up)>0.5, costs {cfg.evaluation.cost_bps_per_turnover}+"
                  f"{cfg.evaluation.slippage_bps} bps per unit turnover)", "", md_table(pd.DataFrame(rows)), ""]
        vb = _read(run, f"var_backtest_{period}.csv")
        if vb is not None:
            s += [f"## 8{'a' if period == 'dev' else 'b'}. 95% VaR backtest from volatility forecasts ({period}; "
                  "Kupiec test on non-overlapping windows)", "", md_table(vb), ""]
    out.write_text("\n".join(s), encoding="utf-8")
    return out
